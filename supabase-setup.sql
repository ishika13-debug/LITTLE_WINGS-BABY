-- Run this once in Supabase Dashboard > SQL Editor.
create table if not exists public.contact_messages (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(btrim(name)) between 1 and 120),
  email text not null check (char_length(btrim(email)) between 3 and 320),
  topic text not null check (char_length(btrim(topic)) between 1 and 100),
  message text not null check (char_length(btrim(message)) between 1 and 5000),
  created_at timestamptz not null default now()
);

alter table public.contact_messages enable row level security;
grant usage on schema public to anon, authenticated;
revoke all on public.contact_messages from anon, authenticated;
grant insert (name, email, topic, message) on public.contact_messages to anon, authenticated;

drop policy if exists "Allow validated contact submissions" on public.contact_messages;
create policy "Allow validated contact submissions"
  on public.contact_messages
  for insert
  to anon, authenticated
  with check (
    char_length(btrim(name)) between 1 and 120
    and char_length(btrim(email)) between 3 and 320
    and char_length(btrim(topic)) between 1 and 100
    and char_length(btrim(message)) between 1 and 5000
  );
